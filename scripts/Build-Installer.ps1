#requires -Version 7.0
param([string]$OutputRoot = 'artifacts/release', [switch]$SkipPublish)
. "$PSScriptRoot/Common.ps1"
function Quote-Bash([string]$Value) { return "'" + $Value.Replace("'", "'\''") + "'" }
function ConvertTo-WslPath([string]$Value) {
    $absolute = [System.IO.Path]::GetFullPath($Value, $ProjectRoot)
    if ($absolute -notmatch '^([A-Za-z]):\\(.*)$') { throw 'WSL 用のドライブパスが必要です。' }
    return '/mnt/' + $Matches[1].ToLowerInvariant() + '/' + $Matches[2].Replace('\', '/')
}
function Escape-Nsis([string]$Value) { return $Value.Replace('$', '$$').Replace('"', '$\"') }

Push-Location $ProjectRoot
try {
    if (!$SkipPublish) { & "$PSScriptRoot/Publish.ps1" -OutputRoot $OutputRoot }
    [xml]$project = Get-Content 'src/sarupdf/sarupdf.csproj' -Raw
    $version = $project.Project.PropertyGroup.Version
    $output = [System.IO.Path]::GetFullPath($OutputRoot, $ProjectRoot)
    $payload = Join-Path $output "SaruPDF-$version-win-x64"
    if (!(Test-Path (Join-Path $payload 'SaruPDF.exe'))) { throw '配布ファイルがありません。Publish.ps1 を実行してください。' }
    $compiler = Join-Path $ProjectRoot '.tools/nsis-root/usr/bin/makensis'
    if (!(Test-Path $compiler)) { throw 'scripts/Install-InstallerTools.ps1 を実行してください。' }

    # Delete only files shipped by this installer, never recursively delete INSTDIR.
    $manifest = Join-Path $output 'uninstall-files.nsh'
    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add('; Generated by Build-Installer.ps1. Exact installed-file deletion only.')
    foreach ($file in Get-ChildItem -LiteralPath $payload -File -Recurse) {
        $relative = [System.IO.Path]::GetRelativePath($payload, $file.FullName)
        if ($relative.StartsWith('..') -or [System.IO.Path]::IsPathRooted($relative)) { throw 'Payload path escaped its directory.' }
        $lines.Add('Delete "$INSTDIR\' + (Escape-Nsis $relative) + '"')
    }
    foreach ($dir in Get-ChildItem -LiteralPath $payload -Directory -Recurse | Sort-Object { $_.FullName.Length } -Descending) {
        $relative = [System.IO.Path]::GetRelativePath($payload, $dir.FullName)
        $lines.Add('RMDir "$INSTDIR\' + (Escape-Nsis $relative) + '"')
    }
    [System.IO.File]::WriteAllLines($manifest, $lines, [System.Text.UTF8Encoding]::new($false))
    $rootWsl = Quote-Bash (ConvertTo-WslPath $ProjectRoot)
    $nsisDir = Quote-Bash (ConvertTo-WslPath (Join-Path $ProjectRoot '.tools/nsis-root/usr/share/nsis'))
    $compilerWsl = Quote-Bash (ConvertTo-WslPath $compiler)
    $arguments = @(
        '-V3', '-WX', "-DPRODUCT_VERSION=$version",
        "-DPAYLOAD_DIR=$(ConvertTo-WslPath $payload)",
        "-DOUTPUT_FILE=$(ConvertTo-WslPath (Join-Path $output "SaruPDF-$version-Setup-x64.exe"))",
        "-DUNINSTALL_MANIFEST=$(ConvertTo-WslPath $manifest)", 'installer/SaruPDF.nsi'
    ) | ForEach-Object { Quote-Bash $_ }
    $command = "cd $rootWsl && NSISDIR=$nsisDir $compilerWsl " + ($arguments -join ' ')
    & wsl.exe bash -lc $command
    if ($LASTEXITCODE -ne 0) { throw 'インストーラーのコンパイルに失敗しました。' }
    Get-FileHash -LiteralPath (Join-Path $output "SaruPDF-$version-Setup-x64.exe") -Algorithm SHA256 | Format-List
    [string[]]$checksums = @("SaruPDF-$version-Setup-x64.exe") | ForEach-Object {
        $hash = Get-FileHash -LiteralPath (Join-Path $output $_) -Algorithm SHA256
        $hash.Hash.ToLowerInvariant() + '  ' + $_
    }
    [System.IO.File]::WriteAllLines((Join-Path $output "SaruPDF-$version-SHA256SUMS.txt"), $checksums, [System.Text.UTF8Encoding]::new($false))
} finally { Pop-Location }
